def obj(**k):
    return ",".join("%s,%s" % (kk[1:], v) for kk, v in k.items())

def level(objs):
    return "kA2,0,kA4,0;" + ";".join(objs) + ";"

def run(objs, inputs, ticks, trackg=0):
    tmp = tempfile.mkdtemp(prefix="su_")
    s = level(objs)
    header, O = gdlevel.parse_objects(s)
    P.apply_header(s)
    cwd = os.getcwd(); os.chdir(APP + "/engine")
    try: L = P.Level(O)
    finally: os.chdir(cwd)
    st = P.Player(0.0, 15.0, speed=1, mini=False, upside=False, mode="cube"); st.hit_ground(); st.bounds_around(15.0)
    export_lib.dict_to_txt(export_lib.level_dict(P, L, st), tmp + "/lv.txt")
    open(tmp + "/r.txt", "w").write("XEND 1e18\nSTARTMODE 0\nENDMODES 0 1 2 3 4 5 6 7\nENVMODES \nBAN \nCOSTS 24 24 14.0 1.0\n")
    inp = ["0"] * ticks
    for a, b in inputs:
        for t in range(a, min(b, ticks)): inp[t] = "1"
    open(tmp + "/in.txt", "w").write(" ".join(inp))
    env = dict(os.environ, PROBE="1", TRACK="1", TRACKG=str(trackg))
    subprocess.run([NEW, tmp + "/lv.txt", tmp + "/r.txt", tmp + "/in.txt", tmp + "/o.txt"], env=env, check=True)
    T = []; G = []; alive = None
    for l in open(tmp + "/o.txt", encoding="utf-8", errors="replace"):
        a = l.split()
        if a[0] == "T": T.append((float(a[1]), float(a[2])))
        elif a[0] == "G": G.append((float(a[2]), float(a[3]), a[4] == "1"))
        elif a[0] == "ALIVE": alive = (int(a[1]), a[2] == "1", float(a[3]))
    return alive, T, G, L

