"""showcase_patch.py — 쇼케이스 영상은 받은 레벨 파일(sac3.txt)과 버전이 다른 곳이 있음. 영상에서 재서 레벨을 고침 (사용자 선택: 쇼케이스대로)
모든 값은 쇼케이스 영상 측정값 (추정, 오차 ±5 정도)"""
REMOVE = [  # (ID, x, y): 쇼케이스 30.70초 화면에 안 보이는 아래쪽 블록·경사 (그 자리에 볼 포탈과 빈 공간)
    ("469", 9674.5, 1050.65), ("469", 9704.5, 1050.65), ("470", 9689.5, 1035.65),
    ("1339", 9689.5, 990.65), ("1339", 9719.5, 990.65), ("1339", 9674.5, 1005.65), ("1339", 9734.5, 1005.65),
]
MOVE = [  # (ID, x, y, 새 y): 텔레포트 트리거(그룹 241) 도착점. 쇼케이스 첫째 높이(30.36~30.48초)와 맞추면 한 칸(30) 위
    ("2069", 9599.5, 1125.65, 1155.65),
]
ADD = [
    {"1": "47", "2": "9650", "3": "1050", "6": "15", "128": "0.75", "129": "0.75"},   # 볼 포탈: 링 아래 끝 (9640,1019)~위 끝 (9656,1082)
    {"1": "1339", "2": "9757", "3": "1035"},                                         # 오르막 경사 (9736,1023)~(9785,1049)
    {"1": "1", "2": "9802", "3": "1035"},                                             # 경사 끝 평평한 블록 (윗면 1049, x 9815까지)
]

# 작은 가시(392)를 90·270도 돌린 것: 히트박스를 안 돌린 것(가로 2.6, 세로 4.8)으로 봄 (추정)
# 근거: 쇼케이스 79.45~79.6초·80.9초 — 폭 27 스파이더가 돌린 392 두 줄 사이 틈(돌린 히트박스면 26.2)을 위로 지나감.
# 레벨 전체에 적용해도 파트 1~5 경로는 그대로 통과함 (확인)
NOSWAP = [("392", -1e9, 1e9, -1e9, 1e9)]

def apply(objs, num):
    out = []
    for o in objs:
        if any(o['1'] == i and abs(num(o, '2') - x) < 0.01 and abs(num(o, '3') - y) < 0.01 for i, x, y in REMOVE):
            continue
        for i, x, y, ny in MOVE:
            if o['1'] == i and abs(num(o, '2') - x) < 0.01 and abs(num(o, '3') - y) < 0.01:
                o = dict(o); o['3'] = str(ny)
        for i, x0, x1, y0, y1 in NOSWAP:
            if o['1'] == i and x0 <= num(o, '2') <= x1 and y0 <= num(o, '3') <= y1:
                o = dict(o); o['_noswap'] = '1'
        out.append(o)
    return out + [dict(a) for a in ADD]
